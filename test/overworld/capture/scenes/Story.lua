-- Story screen (the Start menu's quest icon): region overview, detail pages and the
-- destination map, opened from Pallet. Entry from StoryOverviewLine.lua.
local F, S, X = dofile(os.getenv("REC_TOOLS") .. "/Show.lua")("Story")
local function inStory() return F.cb2() == (S.CB2_Story & ~1) end

F.run(function()
  X.rec(false)
  assert(F.boot(100), "boot")
  X.normalText()
  F.check("Pallet", X.warp(37, 0, 10, 8))
  F.idle(60)
  X.rec(true); X.mark("story")
  F.press("Start", 2); F.idle(60)
  F.check("Story icon", F.selectStartIcon(6)); F.idle(40)
  F.press("A", 2); F.idle(120)
  F.check("Story opens", inStory())
  F.idle(90); F.shot("overview_kanto")
  X.tap("Down", 90); F.shot("overview_johto")
  X.tap("Down", 90); F.shot("overview_hoenn")
  X.tap("Down", 60)
  X.tap("A", 120); F.shot("detail_1")
  for p = 2, 3 do X.tap("Right", 110); F.shot("detail_" .. p) end
  X.tap("Left", 60); X.tap("Left", 60)
  X.mark("map")
  X.tap("A", 200); F.shot("destination_map")
  F.idle(120)
  X.tap("B", 120)
  X.tap("B", 60)
  X.tap("Down", 60)
  X.tap("A", 120); F.shot("johto_detail")
  X.tap("A", 200); F.shot("johto_map")
  F.idle(100)
  X.tap("B", 100); X.tap("B", 60); X.tap("B", 90)
  for _ = 1, 10 do if F.ensureFree() then break end F.press("B", 2); F.idle(30) end
  F.idle(30)
  X.rec(false)
  F.check("back on the field", F.ow())
  F.finish()
end)
