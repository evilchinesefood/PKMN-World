package.path=assert(os.getenv('PW_FEATURE_LIB'))..'/?.lua;'..package.path
local S,X=require('symbols'),require('feature_symbols')
local F=require('lib').new(S,'SpecialPokemonIconAllocation')
F.run(function()
  assert(F.boot(100),'fresh save did not reach overworld')
  assert(F.ow(),'icon allocation fixture requires idle overworld')
  F.w16(S.gSpecialVar_Result,0)
  F.w32(S.gMain+4,X.hook)
  F.idle(60)
  local result=F.r16(S.gSpecialVar_Result)
  F.L(string.format('icon allocation result %02X, expected 7F',result))
  F.check('four exhausted icon calls preserve sprites; released slots allocate again',result==127)
  F.finish()
end)
